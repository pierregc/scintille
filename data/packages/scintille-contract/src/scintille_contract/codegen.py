"""Generation of Python models, TypeScript types and reference docs from the schemas."""

import json
import shutil
import subprocess
import textwrap

from scintille_contract.schema import NamedType, Node, SchemaSet, ref_name, upper_snake

HEADER = "Generated by `scintille-contract generate` from data/contract/. Do not edit."
DOC_BEGIN = "<!-- BEGIN GENERATED REFERENCE -->"
DOC_END = "<!-- END GENERATED REFERENCE -->"

_PY_CONSTRAINTS = {
    "minimum": "ge",
    "maximum": "le",
    "exclusiveMinimum": "gt",
    "exclusiveMaximum": "lt",
    "pattern": "pattern",
    "minLength": "min_length",
    "maxLength": "max_length",
    "minItems": "min_length",
    "maxItems": "max_length",
}


def _kind(node: Node) -> str:
    if "enum" in node:
        return "enum"
    if "const" in node:
        return "const"
    if node.get("type") == "object":
        return "model"
    return "alias"


def _literal(value: object) -> str:
    return json.dumps(value)


def _binary_layout(node: Node) -> list[tuple[str, str, float]]:
    return [
        (name, prop["x-binary"]["dtype"], prop["x-binary"]["scale"])
        for name, prop in node.get("properties", {}).items()
        if "x-binary" in prop
    ]


# Python


def _py_constraints(node: Node) -> list[str]:
    return [f"{arg}={node[key]!r}" for key, arg in _PY_CONSTRAINTS.items() if key in node]


def _py_type(node: Node) -> str:
    if "$ref" in node:
        return ref_name(node["$ref"])
    if "anyOf" in node:
        return " | ".join(_py_type(option) for option in node["anyOf"])
    if "const" in node:
        return f"Literal[{_literal(node['const'])}]"
    if "enum" in node:
        return f"Literal[{', '.join(_literal(v) for v in node['enum'])}]"
    kind = node.get("type")
    if kind == "array":
        item = node["items"]
        item_type = _py_type(item)
        constraints = _py_constraints(item)
        if constraints:
            item_type = f"Annotated[{item_type}, Field({', '.join(constraints)})]"
        return f"list[{item_type}]"
    if kind == "string" and node.get("format") == "date-time":
        return "AwareDatetime"
    scalars = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}
    if kind == "null":
        return "None"
    if kind in scalars:
        return scalars[kind]
    raise ValueError(f"unsupported schema node: {node}")


def _py_str(text: str, indent: int) -> str:
    lines = textwrap.wrap(text, width=84 - indent, drop_whitespace=False)
    if len(lines) == 1:
        return _literal(text)
    pad = " " * (indent + 4)
    return "(\n" + "\n".join(pad + _literal(line) for line in lines) + "\n" + " " * indent + ")"


def _py_docstring(text: str, indent: int) -> str:
    pad = " " * indent
    lines = textwrap.wrap(text, width=96 - indent)
    if len(lines) == 1:
        return f'{pad}"""{lines[0]}"""'
    return f'{pad}"""' + f"\n{pad}".join(lines) + f'\n{pad}"""'


def _py_named(named: NamedType) -> str:
    node, name = named.node, named.name
    kind = _kind(node)
    out: list[str] = []
    if kind == "enum":
        values = ", ".join(_literal(v) for v in node["enum"])
        out.append(f"{name} = Literal[{values}]")
        out.append(f"{upper_snake(name)}_VALUES: Final[tuple[{name}, ...]] = ({values},)")
    elif kind == "const":
        out.append(f"{name} = Literal[{_literal(node['const'])}]")
        out.append(f"{upper_snake(name)}: Final = {_literal(node['const'])}")
    elif kind == "alias":
        out.append(f"{name} = {_py_type(node)}")
    else:
        out.append(f"class {name}(BaseModel):")
        if "description" in node:
            out.append(_py_docstring(node["description"], 4))
            out.append("")
        out.append('    model_config = ConfigDict(extra="forbid", frozen=True)')
        out.append("")
        required = set(node.get("required", []))
        for prop_name, prop in node["properties"].items():
            py_type = _py_type(prop)
            args = [] if prop.get("type") == "array" else _py_constraints(prop)
            if "description" in prop:
                args.append(f"description={_py_str(prop['description'], 8)}")
            if prop_name not in required:
                py_type = f"{py_type} | None"
                args.insert(0, "default=None")
            value = f" = Field({', '.join(args)})" if args else ""
            out.append(f"    {prop_name}: {py_type}{value}")
        layout = _binary_layout(node)
        if layout:
            out.append("")
            out.append("")
            out.append(f"{upper_snake(name)}_BINARY_LAYOUT: Final[tuple[BinaryColumn, ...]] = (")
            for column, dtype, scale in layout:
                out.append(f"    BinaryColumn({column!r}, {dtype!r}, {scale!r}),")
            out.append(")")
    if kind != "model" and "description" in node:
        out.append(_py_docstring(node["description"], 0))
    return "\n".join(out)


def python_module(schemas: SchemaSet) -> str:
    parts = [
        f'"""{HEADER}"""',
        "",
        "from typing import Annotated, Final, Literal, NamedTuple",
        "",
        "from pydantic import AwareDatetime, BaseModel, ConfigDict, Field",
        "",
        "",
        "class BinaryColumn(NamedTuple):",
        '    """Storage of one chunk column: stored = round(value / scale) as dtype."""',
        "",
        "    name: str",
        "    dtype: str",
        "    scale: float",
    ]
    for named in schemas.types:
        parts.append("\n\n" + _py_named(named))
    return _ruff_format("\n".join(parts) + "\n")


def _ruff_format(source: str) -> str:
    ruff = shutil.which("ruff")
    if ruff is None:
        raise RuntimeError("ruff is required to format generated code; run through `uv run`")
    result = subprocess.run(
        [ruff, "format", "--stdin-filename", "models.py", "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout


# TypeScript


def _ts_type(node: Node) -> str:
    if "$ref" in node:
        return ref_name(node["$ref"])
    if "anyOf" in node:
        return " | ".join(_ts_type(option) for option in node["anyOf"])
    if "const" in node:
        return _literal(node["const"])
    if "enum" in node:
        return " | ".join(_literal(v) for v in node["enum"])
    kind = node.get("type")
    if kind == "array":
        item = _ts_type(node["items"])
        return f"({item})[]" if "|" in item else f"{item}[]"
    scalars = {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }
    if kind in scalars:
        return scalars[kind]
    raise ValueError(f"unsupported schema node: {node}")


def _ts_doc(node: Node, indent: str = "") -> list[str]:
    if "description" not in node:
        return []
    return [f"{indent}/** {node['description']} */"]


def _ts_named(named: NamedType) -> str:
    node, name = named.node, named.name
    kind = _kind(node)
    out: list[str] = []
    if kind == "enum":
        values = ", ".join(_literal(v) for v in node["enum"])
        out.append(f"export const {upper_snake(name)}_VALUES = [{values}] as const;")
        out += _ts_doc(node)
        out.append(f"export type {name} = (typeof {upper_snake(name)}_VALUES)[number];")
    elif kind == "const":
        out += _ts_doc(node)
        out.append(f"export const {upper_snake(name)} = {_literal(node['const'])};")
        out.append(f"export type {name} = typeof {upper_snake(name)};")
    elif kind == "alias":
        out += _ts_doc(node)
        out.append(f"export type {name} = {_ts_type(node)};")
    else:
        out += _ts_doc(node)
        out.append(f"export interface {name} {{")
        required = set(node.get("required", []))
        for prop_name, prop in node["properties"].items():
            out += _ts_doc(prop, "  ")
            optional = "" if prop_name in required else "?"
            out.append(f"  {prop_name}{optional}: {_ts_type(prop)};")
        out.append("}")
        layout = _binary_layout(node)
        if layout:
            out.append("")
            out.append(f"export const {upper_snake(name)}_BINARY_LAYOUT = [")
            for column, dtype, scale in layout:
                out.append(f'  {{ name: "{column}", dtype: "{dtype}", scale: {scale!r} }},')
            out.append("] as const;")
    return "\n".join(out)


def typescript_module(schemas: SchemaSet) -> str:
    parts = [f"// {HEADER}"]
    parts += [_ts_named(named) for named in schemas.types]
    return "\n\n".join(parts) + "\n"


# Markdown reference


def _md_type(node: Node) -> str:
    if "$ref" in node:
        target = ref_name(node["$ref"])
        return f"[{target}](#{target.lower()})"
    if "anyOf" in node:
        return " or ".join(_md_type(option) for option in node["anyOf"])
    if "const" in node:
        return f"`{_literal(node['const'])}`"
    kind = node.get("type")
    if kind == "array":
        return f"array of {_md_type(node['items'])}"
    if kind == "string" and "format" in node:
        return f"string ({node['format']})"
    return str(kind)


def _md_constraints(node: Node) -> str:
    target = node["items"] if node.get("type") == "array" else node
    parts = [f"{key} `{target[key]}`" for key in _PY_CONSTRAINTS if key in target]
    if node.get("uniqueItems"):
        parts.append("unique items")
    return ", ".join(parts)


def _md_named(named: NamedType) -> str:
    node, name = named.node, named.name
    kind = _kind(node)
    out = [f"### {name}", "", f"Defined in `data/contract/{named.file}`."]
    if "description" in node:
        out += ["", node["description"]]
    out.append("")
    if kind == "enum":
        out += ["| Index | Value |", "|---|---|"]
        out += [f"| {i} | `{v}` |" for i, v in enumerate(node["enum"])]
    elif kind == "const":
        out.append(f"Value: `{node['const']}`.")
    elif kind == "alias":
        out.append(f"Type: {_md_type(node)}.")
    else:
        required = set(node.get("required", []))
        out += ["| Field | Type | Required | Constraints | Description |", "|---|---|---|---|---|"]
        for prop_name, prop in node["properties"].items():
            out.append(
                f"| `{prop_name}` | {_md_type(prop)} | {'yes' if prop_name in required else 'no'}"
                f" | {_md_constraints(prop)} | {prop.get('description', '')} |"
            )
        layout = _binary_layout(node)
        if layout:
            out += ["", "Binary layout, in order:", ""]
            out += ["| Column | dtype | scale |", "|---|---|---|"]
            out += [f"| `{c}` | {d} | {s!r} |" for c, d, s in layout]
    return "\n".join(out)


def markdown_reference(schemas: SchemaSet) -> str:
    intro = (
        f"Contract version **{schemas.version}**. This section is generated from the schemas; "
        "edit the schemas, then run `uv run scintille-contract generate`."
    )
    return "\n\n".join([intro, *(_md_named(named) for named in schemas.types)])


def render_doc(doc: str, schemas: SchemaSet) -> str:
    """Replace the generated reference section of the hand-written doc."""
    head, sep, rest = doc.partition(DOC_BEGIN)
    _, sep_end, tail = rest.partition(DOC_END)
    if not sep or not sep_end:
        raise ValueError("doc is missing the generated reference markers")
    return f"{head}{DOC_BEGIN}\n\n{markdown_reference(schemas)}\n\n{DOC_END}{tail}"
